export type MessageKey = keyof typeof messages;

export function translate(
  locale: "zh-CN" | "en",
  key: MessageKey,
  params: Record<string, string | number> = {},
): string {
  const value: string = locale === "zh-CN" ? messages[key] : key;
  return value.replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    params[name] === undefined ? placeholder : String(params[name]),
  );
}

export function translateText(locale: "zh-CN" | "en", value: string): string {
  return Object.prototype.hasOwnProperty.call(messages, value)
    ? translate(locale, value as MessageKey)
    : value;
}

let currentLocale: "zh-CN" | "en" = "en";
export function setMessageLocale(locale: "zh-CN" | "en") {
  currentLocale = locale;
}
export function translateCurrent(key: MessageKey, params?: Record<string, string | number>) {
  return translate(currentLocale, key, params);
}
export function translateCurrentText(value: string) {
  return translateText(currentLocale, value);
}
